"""Runtime checks for fixed interactive SQL, isolated schemas and two-session probes."""
import json
import subprocess
import time

FIXTURE = '''
CREATE TABLE customers(customer_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_name text, email text);
INSERT INTO customers(customer_id,customer_name,email) VALUES(101,'Анна','a@example.test'),(102,'Иван','b@example.test');
CREATE TABLE products(product_id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, product_name text, price numeric, category_id int);
INSERT INTO products VALUES(101,'A',1000,1),(102,'B',1500,1),(103,'C',500,2);
CREATE TABLE orders(order_id int PRIMARY KEY,customer_id int,created_at timestamp,status text,paid_at timestamp);
INSERT INTO orders VALUES(5001,101,'2026-01-10','paid',NULL),(5002,101,'2026-01-11','new',NULL),(5003,102,'2026-02-10','paid',NULL);
CREATE TABLE order_items(order_item_id int,order_id int,product_id int,quantity int,unit_price numeric);
INSERT INTO order_items VALUES(1,5001,101,2,10),(2,5001,102,1,5),(3,5002,101,1,10),(4,5003,101,1,20);
CREATE TABLE payments(payment_id int,order_id int,status text,amount numeric);
INSERT INTO payments VALUES(1,5001,'succeeded',10),(2,5001,'succeeded',15),(3,5003,'failed',20);
CREATE TABLE inventory(product_id int,quantity int);
INSERT INTO inventory VALUES(101,5);
CREATE TABLE accounts(id int,balance int);
INSERT INTO accounts VALUES(1,100),(2,0);
CREATE VIEW order_totals AS SELECT o.order_id,o.customer_id,o.created_at,SUM(i.quantity*i.unit_price) AS total,SUM(i.quantity*i.unit_price) AS amount FROM orders o JOIN order_items i ON i.order_id=o.order_id GROUP BY o.order_id,o.customer_id,o.created_at;
'''

def verify_exercises(root,client,command,output,records,env,exercise_ids=None):
    entries=json.loads((root/'interactive_contracts.json').read_text(encoding='utf-8'))
    psql=client+['-A','-t','-q','-F','|']
    def check(label,sql,expected=None):
        # psql's Windows command-line conversion is not UTF-8; use an explicit UTF-8 SQL file.
        sqlfile=output/(label+'.sql')
        sqlfile.write_text(sql,encoding='utf-8')
        result=command(psql+['-f',sqlfile],120)
        lines=[line for line in result.stdout.strip().splitlines() if line.strip()]
        passed=result.returncode==0 and (expected is None or lines[-len(expected):]==expected)
        log=output/(label+'.log')
        log.write_text(result.stdout+result.stderr+ ('\nEXPECTED: '+json.dumps(expected,ensure_ascii=False) if expected else ''),encoding='utf-8')
        records.append({'label':label,'exitCode':0 if passed else (result.returncode or 1),'log':str(log),'expected':expected})
        print(label,'PASS' if passed else 'FAIL',flush=True)
        return passed
    check('exercise-create-report-role',"DO $$ BEGIN IF NOT EXISTS(SELECT FROM pg_roles WHERE rolname='report_reader') THEN CREATE ROLE report_reader; END IF; END $$;")
    for entry in entries:
        e=entry['exercise'];kind=e['type'];eid=e['id']
        if exercise_ids is not None and eid not in exercise_ids:continue
        if kind not in ('code-order','code-debug'):continue
        schema='audit_'+eid.replace('sql-foundations-','').replace('-','_')
        check(eid+'-setup',f'CREATE SCHEMA {schema}; SET search_path={schema},pg_catalog;'+FIXTURE)
        try:
            if kind=='code-order':
                fragments={x['id']:x['code'] for x in e['content']['fragments']}
                programs=['\n'.join(fragments[i] for i in order) for order in e['validation']['acceptedOrders']]
            else:
                lines=e['content']['code'].splitlines();fixid=e['validation']['acceptedFixes']['error-1'][0]
                lines[e['content']['errors'][0]['location']['line']-1]=next(x['code'] for x in e['content']['fixOptions'] if x['id']==fixid)
                programs=['\n'.join(lines)]
            for i,code in enumerate(programs):
                code=code.replace('view_lab.',schema+'.').replace('shopdb_ddl.',schema+'.').replace('reporting.',schema+'.').replace('SCHEMA reporting ',f'SCHEMA {schema} ')
                pre=''
                if eid=='sql-foundations-m08-ex01' or eid=='sql-foundations-m08-ex03':pre='DROP TABLE products;'
                if eid=='sql-foundations-m13-ex02':pre='DROP VIEW order_totals;'
                # Most fixtures are rollback-scoped; the boundary exercise deliberately includes COMMIT.
                prefix=f'SET search_path={schema},pg_catalog;'
                if eid=='sql-foundations-m12-ex03':
                    check(eid+f'-solution-{i+1}',prefix+code+' SELECT id,balance FROM accounts ORDER BY id;', ['1|90','2|10'])
                else:
                    suffix=''
                    expected=None
                    if eid=='sql-foundations-m02-ex03':expected=['102|1500']
                    if eid=='sql-foundations-m03-ex05':expected=['2.5000000000000000']
                    if eid=='sql-foundations-m04-ex03':expected=['paid|2']
                    if eid=='sql-foundations-m09-ex05':expected=['5001|Анна','5002|Анна','5003|Иван'];suffix=' SELECT * FROM order_contacts ORDER BY order_id;'
                    if eid=='sql-foundations-m16-ex03':expected=['25']
                    check(eid+f'-solution-{i+1}',prefix+'BEGIN;'+pre+code+suffix,expected)
                    # Closing the psql session rolls back the uncommitted fixture changes.
        finally:
            check(eid+'-cleanup',f'DROP SCHEMA {schema} CASCADE;')

    if exercise_ids is not None:return

    # Actual SQL for every executable trace (including intermediate outputs).
    traces={
    'm04-ex04': ['3|2|30|15.0000000000000000'],
    'm05-ex02': ['1|10','1|11','2|12'],
    'm05-ex05': ['1|10','1|20','1|30','2|10','2|20','2|30'],
    'm06-ex02': ['30'],
    'm06-ex06': ['t|f|t'],
    'm07-ex06': ['7'],
    'm08-ex06': None,
    'm11-ex04': ['11|1|1|1','12|2|1|1','13|3|3|2','14|4|4|3'],
    'm11-ex05': ['1|10','2|30','3|35','4|32'],
    'm12-ex04': ['1'],
    'm12-ex07': ['2'],
    'm13-ex04': ['100','150'],
    }
    for suffix,expected in traces.items():
        e=next(row['exercise'] for row in entries if row['exercise']['id']=='sql-foundations-'+suffix)
        code=e['content']['code']
        schema='audit_trace_'+suffix.replace('-','_')
        check(suffix+'-trace-setup',f'CREATE SCHEMA {schema};')
        try:
            code=code.replace('public.',schema+'.')
            if suffix=='m08-ex06':
                code=code.replace('TRUNCATE t;','SELECT id FROM t;\nTRUNCATE t;').replace('DROP TABLE t;',"SELECT count(*) FROM t;\nDROP TABLE t;\nSELECT to_regclass('t') IS NULL;")
                expected=['2','0','t']
            if suffix=='m12-ex04':code=code.replace('COMMIT;','SELECT x FROM t ORDER BY x;\nCOMMIT;');expected=['1','1']
            check(suffix+'-trace-runtime',f'SET search_path={schema},pg_catalog;'+code,expected)
        finally:check(suffix+'-trace-cleanup',f'DROP SCHEMA {schema} CASCADE;')

    # Conceptual traces have explicit, independently calculated probes rather than invented execution.
    check('m09-ex02-closure',"WITH RECURSIVE deps(a,b) AS (VALUES ('A','B'),('B','C')), closure(x) AS (VALUES ('A') UNION SELECT d.b FROM closure c JOIN deps d ON d.a=c.x) SELECT string_agg(x,',' ORDER BY x) FROM closure;",['A,B,C'])
    check('m09-ex03-first-normal-form',"SELECT 1,x::int FROM unnest(string_to_array('10,20',',')) x ORDER BY x::int;",['1|10','1|20'])
    check('m10-ex04-tree',"WITH RECURSIVE nodes(id,parent) AS (VALUES (1,NULL::int),(2,1),(3,1),(4,2)), walk(id,depth) AS (SELECT id,0 FROM nodes WHERE id=1 UNION ALL SELECT n.id,w.depth+1 FROM nodes n JOIN walk w ON n.parent=w.id) SELECT id,depth FROM walk ORDER BY depth,id;",['1|0','2|1','3|1','4|2'])
    check('m14-ex03-plan-arithmetic','SELECT 2 * 3;', ['6'])
    check('m15-ex04-rls-role',"BEGIN; SET LOCAL ROLE shopdb_runtime; SELECT set_config('shopdb.tenant_id','101',true); SELECT bool_and(tenant_id=101) FROM security_lab.tenant_orders; ROLLBACK;",['101','t'])

    # Two real sessions: observe a committed change and a bounded row-lock wait.
    check('concurrency-setup','CREATE TABLE public.audit_concurrency(id int PRIMARY KEY,balance int); INSERT INTO public.audit_concurrency VALUES(1,100);')
    capture=output/'read-committed-session1.log'
    with capture.open('w',encoding='utf-8') as stream:
        first=subprocess.Popen([str(x) for x in psql]+['-c','BEGIN ISOLATION LEVEL READ COMMITTED; SELECT balance FROM public.audit_concurrency WHERE id=1; SELECT pg_advisory_lock(7654321); SELECT pg_sleep(3); SELECT balance FROM public.audit_concurrency WHERE id=1; COMMIT;'],env=env,stdout=stream,stderr=stream)
        # Poll a specific advisory marker instead of assuming process launch implies readiness.
        ready=False
        for _ in range(80):
            probe=command(psql+['-c',"SELECT count(*) FROM pg_locks WHERE locktype='advisory' AND objid=7654321;"])
            if probe.stdout.strip()=='1':ready=True;break
            if first.poll() is not None:break
            time.sleep(.05)
        if ready:check('read-committed-session2','UPDATE public.audit_concurrency SET balance=150 WHERE id=1;')
        first.wait(timeout=20)
    values=[line.strip() for line in capture.read_text(encoding='utf-8').splitlines() if line.strip()]
    ok=ready and first.returncode==0 and values==['100','150']
    records.append({'label':'two-session-read-committed','exitCode':0 if ok else 1,'log':str(capture)})
    print('two-session-read-committed','PASS' if ok else 'FAIL',flush=True)
    locklog=output/'row-lock-session1.log'
    with locklog.open('w',encoding='utf-8') as stream:
        first=subprocess.Popen([str(x) for x in psql]+['-c','BEGIN; UPDATE public.audit_concurrency SET balance=160 WHERE id=1; SELECT pg_advisory_lock(7654322); SELECT pg_sleep(3); ROLLBACK;'],env=env,stdout=stream,stderr=stream)
        ready=False
        for _ in range(80):
            probe=command(psql+['-c',"SELECT count(*) FROM pg_locks WHERE locktype='advisory' AND objid=7654322;"])
            if probe.stdout.strip()=='1':ready=True;break
            if first.poll() is not None:break
            time.sleep(.05)
        second=command(psql+['-c',"SET lock_timeout='300ms'; UPDATE public.audit_concurrency SET balance=170 WHERE id=1;"])
        first.wait(timeout=20)
    lockresult=output/'row-lock-session2.log';lockresult.write_text(second.stdout+second.stderr,encoding='utf-8')
    ok=ready and first.returncode==0 and second.returncode!=0 and 'lock timeout' in second.stderr
    records.append({'label':'two-session-lock-timeout','exitCode':0 if ok else 1,'log':str(lockresult)})
    print('two-session-lock-timeout','PASS' if ok else 'FAIL',flush=True)
    check('concurrency-cleanup','DROP TABLE public.audit_concurrency;')
